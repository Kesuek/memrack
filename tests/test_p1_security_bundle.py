def _loader_of(fake):
    def _loader():
        return fake
    return _loader


def _offer(name, home):
    return {"name": name, "source": "user", "version": "9.9.9",
            "dir": home, "active": False}


def _dock_dir(tmp_path):
    return tmp_path / "plugins" / "memrack" / "backends.d"


def _probe_dock(tmp_path, name="fakesvc"):
    """A real machine-docked draft card + shim pair on file."""
    fake = FakeProvider(name)
    DOCKING.dock(name, probe=True, loader=_loader_of(fake),
                 offers=[_offer(name, str(tmp_path))],
                 hermes_home=str(tmp_path))
    return (_dock_dir(tmp_path) / ("%s.yaml" % name),
            _dock_dir(tmp_path) / ("%s.py" % name))


def _prov(tmp_path):
    prov = mr._MemrackBase(config={})
    prov.initialize(session_id="P1", hermes_home=str(tmp_path))
    return prov


def _status(prov):
    return json.loads(prov.handle_tool_call("memrack_status", {}))


