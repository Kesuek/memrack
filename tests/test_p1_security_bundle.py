class WikiDuck:
    """The episodic route stand (name 'wiki' = the episode route)."""

    name = "wiki"

    def initialize(self, session_id="", hermes_home=None, **kw):
        pass

    def on_turn(self, user, assistant, *, session_id=""):
        return "WIKI-TURN"


def _racked(tmp_path, fake, card):
    prov = _prov(tmp_path)
    member = PROXY.CatalogProxyBackend(provider=fake)
    member.name = fake.name
    member.manifest = dict(card)
    prov._rack[member.name] = member
    return prov


def test_forward_turns_gate_routes_turn_to_dock(tmp_path):
    """Gate ON: the turn event reaches the docked member through its on_turn
    pass-through (the provider's sync_turn is proven called) even when the
    canonical episodic route stays None; the route log records the forward."""
    fake = FakeProvider("fakedock")
    prov = _racked(tmp_path, fake, {"forward_turns": True})
    out = prov.sync_turn("user says hi", "assistant replies", session_id="S1")
    assert out is None, "the routed (episodic) receipt stays None — state.db is canonical"
    assert fake.turns == [("user says hi", "assistant replies", "S1")], fake.turns
    log = tmp_path / "plugin-data" / "memrack" / "route_log.jsonl"
    entries = [json.loads(line) for line in log.read_text(encoding="utf-8").splitlines()]
    assert any(e["kind"] == "turn" and "forward" in str(e.get("detail", ""))
               and "fakedock" in str(e.get("backend", "")) for e in entries), entries


def test_without_gate_turn_routing_unchanged(tmp_path):
    """Canon-keeping: no `forward_turns` key on the card means NO turn event,
    exactly as before — no silent copying into the dock."""
    fake = FakeProvider("fakedock")
    prov = _racked(tmp_path, fake, {})
    prov.sync_turn("user says hi", "assistant replies", session_id="S1")
    assert fake.turns == [], fake.turns
    fake2 = FakeProvider("fakedock2")
    prov2 = _racked(tmp_path, fake2, {"forward_turns": False})
    prov2.sync_turn("user", "assistant", session_id="S2")
    assert fake2.turns == [], fake2.turns


def test_gate_forwards_do_not_change_single_result_form(tmp_path):
    """T-038 semantics: the return stays the ROUTED backend's answer; the
    gated forwards ride the route log, never the return value."""
    fake = FakeProvider("fakedock")
    prov = _racked(tmp_path, fake, {"forward_turns": True})
    prov._rack["wiki"] = WikiDuck()
    out = prov.sync_turn("u", "a", session_id="S3")
    assert out == "WIKI-TURN", out
    assert fake.turns == [("u", "a", "S3")], fake.turns


def test_gate_error_is_isolated(tmp_path):
    """One failing gated member never kills the routed path nor the sibling
    forwards (per-backend error isolation, the fan-out law)."""
    fake_ok = FakeProvider("okdock")
    prov = _prov(tmp_path)
    bad = PROXY.CatalogProxyBackend(provider=FakeProvider("baddock"))
    bad.name = "baddock"
    bad.manifest = {"forward_turns": True}
    bad_member = bad

    def _explode(user, assistant, *, session_id=""):
        raise RuntimeError("dock exploded on turn")

    bad_member.on_turn = _explode
    good = PROXY.CatalogProxyBackend(provider=fake_ok)
    good.name = "okdock"
    good.manifest = {"forward_turns": True}
    prov._rack["baddock"] = bad_member
    prov._rack["okdock"] = good
    out = prov.sync_turn("u", "a", session_id="S4")
    assert out is None
    assert fake_ok.turns == [("u", "a", "S4")], \
        "the sibling forward survived the failing member: %r" % (fake_ok.turns,)


def test_status_card_carries_the_turn_gate(tmp_path):
    """The gate is visible on the served card (memrack_status): a gated dock
    carries forward_turns=True, others carry nothing (sparse, additive)."""
    fake = FakeProvider("fakedock")
    prov = _racked(tmp_path, fake, {"forward_turns": True})
    plain = PROXY.CatalogProxyBackend(provider=FakeProvider("plaindock"))
    plain.name = "plaindock"
    prov._rack["plaindock"] = plain
    status = _status(prov)
    cards = dict(status["cards"])   # the cards slot is {name: card}
