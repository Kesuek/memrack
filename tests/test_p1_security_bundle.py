def test_dock_remove_deletes_generated_shim_and_next_session_is_clean(tmp_path):
    """Card + machine-generated shim on file → remove deletes BOTH; the next
    discovery (a fresh registry pass) hosts no provider under that name."""
    card_path, shim_path = _probe_dock(tmp_path)
    assert card_path.exists() and shim_path.exists()
    out = DOCKING.dock_remove("fakesvc", hermes_home=str(tmp_path))
    assert out["removed"] is True, out
    assert not card_path.exists(), "the card leaves"
    assert not shim_path.exists(), "the machine-generated shim leaves too"
    assert "fakesvc.py" in (out.get("removed_shims") or []), out
    discovered = mr.discover_backends(hermes_home=str(tmp_path))
    assert "fakesvc" not in discovered["backends"], discovered["backends"]
    assert not any("fakesvc" in str(e) for e in discovered["errors"]), discovered


def test_dock_remove_keeps_user_owned_module(tmp_path):
    """A user-owned legacy module beside the card is NOT the machine's shim:
    the card leaves, the module STAYS (the legacy contract) and still loads."""
    card_path, shim_path = _probe_dock(tmp_path)
    shim_path.write_text(
        'class UserLegacy:\n    name = "fakesvc"\n\n'
        '    def initialize(self, session_id="", hermes_home=None, **kw):\n'
        '        pass\n\n'
        '    def on_turn(self, user, assistant, *, session_id=""): return None\n'
        '    def on_memory_write(self, *a, **k): return None\n'
        '    def on_session_end(self, *a, **k): return None\n'
        '    def prefetch(self, q, *, session_id=""): return ""\n'
        '    def system_prompt_block(self): return ""\n'
        '    def shutdown(self): pass\n'
        '    def export(self): return {"name": self.name}\n\n\n'
        "def export_backend():\n    return UserLegacy()\n",
        encoding="utf-8")
    out = DOCKING.dock_remove("fakesvc", hermes_home=str(tmp_path))
    assert out["removed"] is True, out
    assert not card_path.exists(), "the card leaves"
    assert shim_path.exists(), "a user-owned module stays (not machine-generated)"
    kept = out.get("kept_shims") or []
    assert any(e["file"] == "fakesvc.py" for e in kept), out
    discovered = mr.discover_backends(hermes_home=str(tmp_path))
    assert "fakesvc" in discovered["backends"], \
        "the legacy module stays loadable (documented legacy contract)"


