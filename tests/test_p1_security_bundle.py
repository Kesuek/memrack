def test_name_law_pattern(tmp_path):
    """The central validator: dots, slashes, traversal and separators are
    outside the law; dashes, underscores, digits and a 64-char length stay
    inside it."""
    for good in ("a", "9lives", "honcho-mem", "fakesvc_2", "a" * 64):
        assert DOCKING._valid_dock_name(good) is True, good
        assert DOCKING._valid_dock_name("disabled-%s" % good) is True, good
    for bad in ("../escape", "..", "/etc/passwd", "sub/dir", "f.yaml",
                "..%2f", "a b", "Bad", "", "a" * 65, "a\\b", "with.dot"):
        assert DOCKING._valid_dock_name(bad) is False, bad


def test_dock_refuses_traversal_name_before_any_flow(tmp_path):
    """`memrack dock ../escape` — even WITH a matching (hostile) offer name,
    the name law refuses first and nothing is written anywhere."""
    bad = "../escape"
    victim = tmp_path / "escape.yaml"
    victim.write_text("keep me\n", encoding="utf-8")
    out = DOCKING.dock(bad, probe=True, loader=_loader_of(FakeProvider(bad)),
                       offers=[_offer(bad, str(tmp_path))],
                       hermes_home=str(tmp_path))
    assert out.get("refused") is True, out
    assert "invalid dock name" in str(out.get("error")), out
    assert victim.read_text(encoding="utf-8") == "keep me\n"
    offer_only = DOCKING.dock(bad, probe=False, offers=[], hermes_home=str(tmp_path))
    assert "invalid dock name" in str(offer_only.get("error")), offer_only


