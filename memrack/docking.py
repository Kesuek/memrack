# these; a catalog entry that only SAYS "memory" does not.
_ABC_REQUIRED_CALLABLES = (
    "is_available", "initialize", "get_tool_schemas", "prefetch",
    "system_prompt_block", "sync_turn", "on_memory_write",
    "on_session_end", "shutdown",
)
_ABC_REPORTED_HOOKS = _ABC_REQUIRED_CALLABLES + (
    "queue_prefetch", "recall_status", "on_pre_compress",
    "on_session_switch", "on_delegation", "handle_tool_call",
)

