"""Docking machine for installed, INACTIVE catalog memory providers.

Design-Contract (source of truth:
~/.hermes/projects/memrack/references/catalog-rack-adapter-design.md —
sections "Grundidee", "Card-Erstellung für angedockte Katalog-Provider",
"Sampling-Bias-Law") + plan .hermes/plans/t033-adapter-impl.md scope 2-4:

- memrack is the active provider; it detects installed catalog providers
  that are NOT active and OFFERS docking (`memrack dock <provider>`) —
  no auto-dock, the user/agent decides.
- the probe instantiates the provider class ISOLATED (hermes-plugins
  doctor pattern; no host injection), checks the ABC occupancy
  (hooks present? prefetch-only vs. query-capable? registered tools ->
  mirror list per the name chain) and writes the DRAFT card
  (derived search modes + effective tool names) plus the drift-recheck
  evidence (probe timestamp + provider version) into
  ``backends.d/<provider>.yaml``.
- best_for / limits stay HUMAN-authored: the DRAFT carries placeholders,
  the review at docking fills them (never machine-guessed).
- provider NOT installed -> refused, fail-closed, Gap-Note; never invent.
- the probe result is the truth (Sampling-Bias-Law): "Context-Engine vs.
  Ranked-Retrieval" is a per-provider probe outcome, never a prior from
  our wiki-memory sample. A catalog entry labelled memory ALONE is no
  qualification — the probe must prove a MemoryProvider ABC behind it.

Grounded host mechanics (read from the Hermes runtime source, NOT invented —
see the scaffold LOG for the reading):

- installed names: plugins.memory.list_memory_provider_names()
  (bundled -> $HERMES_HOME/plugins/memory/<name> user dirs -> pip entry
  points); find_provider_dir(name) resolves one directory.
- inactive check: candidates = installed names minus `_get_active_memory_
  provider()` (config `memory.provider` — normally memrack itself, which is
  therefore never offered by construction).
- isolated instantiation: the real loader path is ``load_memory_provider
  (name, register_skills=False)`` — the loader documents the isolation
  guarantee ("inspecting inactive providers leaves no registry side
  effects"); test doubles pass ``loader``/``offers`` seams (the lazy
  hermes-import paths are never touched hermes-less).
- provider version: the provider's own plugin.yaml manifest `version` (the
  value the plugins hub reads out of the same manifest), with the provider
  instance attribute taking precedence for doubles that carry one.

Pure stdlib at module level (repo suite convention: tests spec-load this
file hermes-less; pyyaml is imported lazily inside the implementation,
exactly like the registry does it).
"""

