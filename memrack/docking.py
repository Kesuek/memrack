_QUERY_SURFACE_CANDIDATES = (
    # Attribute names that mark retrieval beyond the ABC's common surface —
    # the probe records whatever the provider ACTUALLY exposes (evidence),
    # never a generic assumption about the catalog population.
    "search", "query", "search_memory", "search_memories",
    "retrieve", "query_memories",
)

# The ABC hook names the occupancy check verifies. `name` is an attribute
