"""Docking machine for installed, INACTIVE catalog memory providers.

Design-Contract (source of truth:
~/.hermes/projects/memrack/references/catalog-rack-adapter-design.md —
sections "Grundidee", "Card-Erstellung für angedockte Katalog-Provider",
"Sampling-Bias-Law") + plan .hermes/plans/t033-adapter-impl.md scope 2-4:

- memrack is the active provider; it detects installed catalog providers
  that are NOT active and OFFERS docking (`memrack dock <provider>`) —
  no auto-dock, the user/agent decides.
- the probe instantiates the provider class ISOLATED (hermes-plugins
  doctor pattern; no host injection), checks the ABC occupancy
  (hooks present? prefetch-only vs. query-capable? registered tools ->
  mirror list per the name chain) and writes the DRAFT card
  (derived search modes + effective tool names) plus the drift-recheck
  evidence (probe timestamp + provider version) into
  ``backends.d/<provider>.yaml``.
- best_for / limits stay HUMAN-authored: the DRAFT carries placeholders,
  the review at docking fills them (never machine-guessed).
- provider NOT installed -> refused, fail-closed, Gap-Note; never invent.
- the probe result is the truth (Sampling-Bias-Law): "Context-Engine vs.
  Ranked-Retrieval" is a per-provider probe outcome, never a prior from
  our wiki-memory sample. A catalog entry labelled memory ALONE is no
  qualification — the probe must prove a MemoryProvider ABC behind it.

Grounded host mechanics (read from the Hermes runtime source, NOT invented —
see the scaffold LOG for the reading):

- installed names: plugins.memory.list_memory_provider_names()
  (bundled -> $HERMES_HOME/plugins/memory/<name> user dirs -> pip entry
  points); find_provider_dir(name) resolves one directory.
- inactive check: candidates = installed names minus `_get_active_memory_
  provider()` (config `memory.provider` — normally memrack itself, which is
  therefore never offered by construction).
- isolated instantiation: the real loader path is ``load_memory_provider
  (name, register_skills=False)`` — the loader documents the isolation
  guarantee ("inspecting inactive providers leaves no registry side
  effects"); test doubles pass ``loader``/``offers`` seams (the lazy
  hermes-import paths are never touched hermes-less).
- provider version: the provider's own plugin.yaml manifest `version` (the
  value the plugins hub reads out of the same manifest), with the provider
  instance attribute taking precedence for doubles that carry one.

Pure stdlib at module level (repo suite convention: tests spec-load this
file hermes-less; pyyaml is imported lazily inside the implementation,
exactly like the registry does it).
"""

import os
from pathlib import Path

PROXY_BACKEND_MODULE = "_catalog_proxy"
"""The adapter module the draft card's shim resolves to (backends/_catalog_proxy.py).

Deliberate deviation from the scaffold's rename plan (recorded in design.md
## Deviations): the adapter KEEPS its leading underscore — discover_backends()
loads every non-underscore *.py in backends/ as a code-first built-in, and a
library file carrying no provider binding would fail the registry checks on
every host in every session. The draft card's `module` field points at the
per-provider SHIM beside the card, which binds ONE provider name to this
shared adapter file (see _SHIM_TEMPLATE)."""

_SELF = "memrack"
"""The memrack plugin name itself is never a dock candidate (a rack docked
into its own rack is not a thing; the active-provider filter covers the
normal case, this covers the inverted case)."""

_QUERY_SURFACE_CANDIDATES = (
    # Attribute names that mark retrieval beyond the ABC's common surface —
    # the probe records whatever the provider ACTUALLY exposes (evidence),
    # never a generic assumption about the catalog population.
    "search", "query", "search_memory", "search_memories",
    "retrieve", "query_memories",
)

# The ABC hook names the occupancy check verifies. `name` is an attribute
# (property), checked as value — a MemoryProvider-ABC carrier has all of
# these; a catalog entry that only SAYS "memory" does not.
_ABC_REQUIRED_CALLABLES = (
    "is_available", "initialize", "get_tool_schemas", "prefetch",
    "system_prompt_block", "sync_turn", "on_memory_write",
    "on_session_end", "shutdown",
)
_ABC_REPORTED_HOOKS = _ABC_REQUIRED_CALLABLES + (
    "queue_prefetch", "recall_status", "on_pre_compress",
    "on_session_switch", "on_delegation", "handle_tool_call",
)

_SHIM_TEMPLATE = '''"""Auto-generated by the memrack docking machine (draft card %(provider)s).

Per-provider BINDING shim: the shared catalog adapter lives in the memrack
plugin (backends/%(module)s.py); this shim binds THIS provider's name to its
from_dock() entry. The sibling card %(provider)s.yaml owns the recorded
decisions (draft state, mirror decision, forwards) — card edits never need a
shim rewrite. The registry loads the shim THROUGH its manifest; it is skipped
as a code-first drop-in for exactly that reason.
"""

import importlib.util
import pathlib
import sys

_CANDIDATES = (
    # deterministic first: the adapter inside THIS plugin copy, then the
    # generation-time path recorded by the dock machine (fallback).
    pathlib.Path(__file__).resolve().parent.parent / "backends" / "%(module)s.py",
    pathlib.Path(%(adapter_path)r),
)


def _adapter():
    mod = sys.modules.get("memrack_catalog_adapter")
    if mod is not None:
        return mod
    for path in _CANDIDATES:
        if path.is_file():
            spec = importlib.util.spec_from_file_location(
                "memrack_catalog_adapter", path)
            mod = importlib.util.module_from_spec(spec)
            sys.modules["memrack_catalog_adapter"] = mod
            spec.loader.exec_module(mod)
            return mod
    raise ImportError("memrack catalog adapter not found under: "
                      + ", ".join(str(p) for p in _CANDIDATES))


def export_backend():
    return _adapter().from_dock(%(provider)r)
'''


def _utcnow_iso():
    """UTC, microseconds, Z-suffix — the repo-wide evidence timestamp law."""
    import datetime as _dt
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f") + "Z"


def _docked_dir(hermes_home=None):
    """Card directory: $HERMES_HOME/plugins/memrack/backends.d/ — the SAME
    path computation as the provider core's docked_dir() (the docking
    machine stays spec-load independent of the core module; the parity is
    pinned by the tests via the core's own docked_dir)."""
    if hermes_home:
        return Path(hermes_home) / "plugins" / _SELF / "backends.d"
    home = os.environ.get("HERMES_HOME") or Path.home() / ".hermes"
    return Path(home) / "plugins" / _SELF / "backends.d"


def _namechain():
    """The name-chain module, spec-path resolved beside THIS file — no
    package import needed (the same convention the adapter file uses)."""
    import importlib.util
    import sys
    mod = sys.modules.get("memrack_docking_namechain")
    if mod is not None:
        return mod
    spec = importlib.util.spec_from_file_location(
        "memrack_docking_namechain",
        Path(__file__).resolve().parent / "namechain.py")
    if spec is None or spec.loader is None:
        raise ImportError("name chain module not resolvable beside docking.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["memrack_docking_namechain"] = mod
    spec.loader.exec_module(mod)
    return mod


# ── discovery: installed, INACTIVE catalog providers ────────────────────────

def catalog_offers(providers=None, hermes_home=None):
    """Installed, INACTIVE catalog memory providers — the offer list.

    Offer only (design: "offers docking — the user/agent decides", no
    AUTO-dock). Per entry: {name, source, version, dir, active: False}.
    A name here is a CANDIDATE only; the probe still has to prove the
    MemoryProvider ABC (the probe outcome decides).

    ``providers`` is the test-double seam: a pre-collected list of offer
    descriptors standing in for the real plugins.memory scan (the lazy
    hermes import path is never touched while doubles run). The real scan
    follows the hub's own environment-scoped discovery (the profile that
    runs this has its HERMES_HOME set); ``hermes_home`` adds nothing on top
    of that — kept in the signature for interface parity.
    """
    if providers is not None:
        return [dict(entry) for entry in providers]
    hub = _plugins_memory()
    if hub is None:
        return []
    try:
        active = hub._get_active_memory_provider()
    except Exception:
        active = None
    offers = []
    for name in sorted(hub.list_memory_provider_names()):
        if not name or name == active or name == _SELF:
            continue
        provider_dir = _provider_dir(name, hub)
        offers.append({
            "name": name,
            "source": _classify_source(provider_dir, hub),
            "version": _manifest_version(provider_dir),
            "dir": str(provider_dir) if provider_dir else None,
            "active": False,
        })
    return offers


def _plugins_memory():
    """The hermes memory provider hub (`plugins.memory`), or None hermes-less."""
    try:
        from plugins import memory as hub
    except ImportError:
        return None
    return hub


def _provider_dir(name, hub=None):
    hub = hub or _plugins_memory()
    if hub is None:
        return None
    try:
        return hub.find_provider_dir(name)
    except Exception:
        return None


def _classify_source(provider_dir, hub):
    """bundled | user | pip — a directory-level classification, no import."""
    if provider_dir is None:
        return "pip"
    try:
        if str(Path(provider_dir).resolve()).startswith(
                str(hub._MEMORY_PLUGINS_DIR)):
            return "bundled"
    except Exception:
        pass
    return "user"


def _manifest_version(provider_dir):
    """The provider's own plugin.yaml `version` (the hub's manifest value),
    "" honestly when unreadable — never a fabricated number."""
    if provider_dir is None:
        return ""
    try:
        manifest = Path(provider_dir) / "plugin.yaml"
        if not manifest.is_file():
            return ""
        import yaml
        data = yaml.safe_load(manifest.read_text(encoding="utf-8")) or {}
        version = data.get("version") if isinstance(data, dict) else None
        return str(version) if version is not None else ""
    except Exception:
        return ""


def _real_loader(provider_name):
    """The real-path isolated loader (doctor pattern, register_skills=False)."""
    def _load():
        hub = _plugins_memory()
        if hub is None:
            return None    # hermes-less: there is no provider to find — refuse
        return hub.load_memory_provider(provider_name, register_skills=False)
    return _load


# ── the probe: the truth per provider ───────────────────────────────────────

def _occupancy(provider):
    """ABC-Besetzung: hook presence dict + the name attribute as a value."""
    hooks = {}
    missing = []
    for hook in _ABC_REPORTED_HOOKS:
        hooks[hook] = callable(getattr(provider, hook, None))
    for hook in _ABC_REQUIRED_CALLABLES:
        if not hooks[hook]:
            missing.append(hook)
    name_value = getattr(provider, "name", None)
    named = bool(name_value) and not callable(name_value)
    hooks["name"] = named
    return hooks, (not missing and named), ("" if name_value is None else str(name_value))


def _available_of(provider):
    """The ABC availability gate (config/deps only — never network). False
    reports refuse the dock at card time (fail-closed credentials law)."""
    gate = getattr(provider, "is_available", None)
    if not callable(gate):
        return False
    try:
        return bool(gate())
    except Exception:
        return False


def _provider_tools(provider, out=None):
    """(tool name, schema) pairs in EITHER schema shape; duplicates are NOT
    deduplicated — the name chain's uniqueness law wants to see them."""
    fn = getattr(provider, "get_tool_schemas", None)
    if not callable(fn):
        return []
    pairs = []
    for schema in list(fn() or []):
        tool = _namechain().extract_tool_name(schema)
        if tool:
            pairs.append((tool, schema))
    return pairs


def _provider_version(provider_name, provider):
    direct = getattr(provider, "plugin_version", None)
    if isinstance(direct, str) and direct:
        return direct
    return _manifest_version(_provider_dir(provider_name))


def _refused_report(provider_name, reason, *, occupancy=None, version=None):
    return {
        "provider": provider_name,
        "abc_occupied": False,
        "refused": True,
        "gap": reason,
        "hooks": occupancy if occupancy is not None else {},
        "mirror_tools": [],
        "derived_search_modes": [],
        "provider_version": version,
        "evidence": {"probed_at": _utcnow_iso(), "provider_version": version},
    }


def probe(provider_name, *, loader=None, hermes_home=None):
    """Public probe — thin wrapper over the implementation (_probe).

    Keeping the implementation under ``_probe`` avoids the frozen ``probe``
    flag of the dock() signature shadowing this module function inside dock.
    """
    return _probe(provider_name, loader=loader, hermes_home=hermes_home)


def _probe(provider_name, *, loader=None, hermes_home=None):
    """Probe ONE provider in isolation; return the conformance report.

    ``loader`` is the test-double seam: in-process fakes pass a callable —
    () -> provider instance (or raise to model a broken/uninstalled
    provider); the real path uses the plugins.memory doctor pattern with
    register_skills=False (see module docstring). No host injection.

    Report (probe = the truth): {provider, abc_occupied, classification:
    'prefetch-only' | 'query-capable' (per-provider outcome, with the
    evidence), hooks, mirror_tools: [{tool, effective}] (64-cap name chain
    applied), derived_search_modes, provider_version, available, evidence}.
    A provider that is not installed or fails to instantiate: refused,
    fail-closed — the report carries the Gap-Note, no card is written, no
    name is invented. A colliding mirror set aborts with an error
    (the fail-closed law — no mangled names, no winner picks).
    """
    if loader is None:
        loader = _real_loader(provider_name)
    try:
        provider = loader()
    except Exception as exc:
        return _refused_report(
            provider_name,
            "provider instantiation failed in isolation (fail-closed): %s: %s"
            % (type(exc).__name__, exc))
    if provider is None:
        return _refused_report(
            provider_name,
            "provider not installed / not loadable (fail-closed Gap-Note — "
            "nothing invented for a dock that was never proven)")
    hooks, occupied, provider_name_attr = _occupancy(provider)
    version = _provider_version(provider_name, provider)
    if not occupied:
        return _refused_report(
            provider_name,
            "the probed object is no MemoryProvider-ABC (categories lie; the "
            "probe must prove the ABC — missing: %s)"
            % (", ".join(h for h in _ABC_REQUIRED_CALLABLES if not hooks[h]) or "name"),
            occupancy=hooks, version=version)

    classification = "query-capable" if (_provider_tools(provider) or
                                        [m for m in _QUERY_SURFACE_CANDIDATES
                                         if callable(getattr(provider, m, None))]) \
        else "prefetch-only"
    query_surface = [m for m in _QUERY_SURFACE_CANDIDATES
                     if callable(getattr(provider, m, None))]
    tools = _provider_tools(provider)
    available = _available_of(provider)

    mirror_list = []
    if tools:
        chain = _namechain()
        tool_names = [name for name, _ in tools]
        mapping = chain.mirror_tool_names(
            provider_name or provider_name_attr, tool_names)
        try:
            # per-OCCURRENCE uniqueness: a provider registering the same tool
            # name twice is itself the collision (fail-closed, never dedupe)
            chain.ensure_unique([mapping[name] for name in tool_names],
                                origin="probe of %r" % provider_name)
        except chain.MirrorNameError as exc:
            return {
                "provider": provider_name, "abc_occupied": True,
                "refused": True, "error": "mirror name collision (fail-closed): %s"
                % exc,
                "classification": classification, "hooks": hooks,
                "mirror_tools": [], "derived_search_modes": [],
                "provider_version": version, "available": available,
                "evidence": {"probed_at": _utcnow_iso(),
                             "provider_version": version,
                             "classification": classification,
                             "tool_count": len(tools),
                             "query_surface": query_surface,
                             "available": available},
            }
        mirror_list = [{"tool": tool, "effective": effective}
                       for tool, effective in sorted(mapping.items())]

    return {
        "provider": provider_name,
        "abc_occupied": True,
        "classification": classification,
        "hooks": hooks,
        "mirror_tools": mirror_list,
        "derived_search_modes": [],   # no generic claim: per-provider bridges stay
                                      # deliberate work (Sampling-Bias-Law scope rule)
        "provider_version": version,
        "available": available,
        "evidence": {"probed_at": _utcnow_iso(), "provider_version": version,
                     "classification": classification, "tool_count": len(tools),
                     "query_surface": query_surface, "available": available},
    }


# ── the draft card + its binding shim ───────────────────────────────────────

def draft_card(provider_name, probe_report):
    """Compose the DRAFT card mapping from a probe report (pure function).

    Fields per design: name/provider identity, module = the per-provider
    shim (resolves beside the card like every manifest), search modes
    derived from the probe outcome (none generically — honest scope rule:
    no invented query bridges), mirrored effective tool names, draft
    marker, best_for/limits as honest PLACEHOLDERS (human review fills
    them before the card is final), evidence: {probed_at, provider_version
    + the classification facts}, revisions: [] (drift-recheck appends).
    """
    mirror_tools = {entry["tool"]: entry["effective"]
                    for entry in (probe_report.get("mirror_tools") or [])}
    card = {
        "name": str(provider_name),
        "provider": str(provider_name),
        "module": "%s.py" % provider_name,      # the shim beside the card
        "draft": True,
        "best_for": "PLACEHOLDER — human-authored at the dock review "
                    "(the code claims nothing)",
        "limits": "PLACEHOLDER — human-authored at the dock review",
        "search": list(probe_report.get("derived_search_modes") or []),
        "evidence": dict(probe_report.get("evidence") or {}),
        "revisions": [],
    }
    if mirror_tools:
        card["mirror_tools"] = mirror_tools
        card["mirror_decision"] = "mirror"   # the recorded decision (the derivation)
    # forward_writes stays ABSENT in the draft: undecided = fail-closed
    # retrieval-only; the review records it explicitly when compatible.
    return card


def _atomic_write(path, text, *, mode=0o600):
    """Write ATOMICALLY (tmp in the same directory, then os.replace) — the
    same discipline the provider core applies to its config writers. Docking
    artifacts are PRIVATE card data: file 0600, the card directory 0700."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.parent / (path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    try:
        os.chmod(tmp, mode)
    except OSError:
        pass
    try:
        os.chmod(path.parent, 0o700)
    except OSError:
        pass
    os.replace(tmp, path)


def _read_card(path):
    """One dock card off disk; None when absent/empty; the parse raises —
    callers decide what honesty needs (no silent invention)."""
    if not path.exists():
        return None
    import yaml
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def write_draft_card(provider_name, probe_report, *, hermes_home=None):
    """Write the DRAFT card at backends.d/<provider>.yaml + its shim.

    Presence semantics like every docked backend (the registry law: the
    file being there = registered next session). The shim binds the shared
    adapter deterministically (this plugin copy first, then the recorded
    generation-time path) — one adapter file, many provider cards.
    """
    import yaml
    dock = _docked_dir(hermes_home)
    card = draft_card(provider_name, probe_report)
    card_path = dock / ("%s.yaml" % provider_name)
    _atomic_write(card_path, yaml.dump(card, default_flow_style=False,
                                       allow_unicode=True, sort_keys=False))
    adapter_path = (Path(__file__).resolve().parent.parent / "backends" /
                    (PROXY_BACKEND_MODULE + ".py"))
    shim_path = dock / ("%s.py" % provider_name)
    shim = _SHIM_TEMPLATE % {
        "provider": str(provider_name),
        "module": PROXY_BACKEND_MODULE,
        "adapter_path": str(adapter_path),
    }
    _atomic_write(shim_path, shim, mode=0o600)
    return {"file": str(card_path), "shim": str(shim_path), "card": card}


# ── the dock dispatcher ─────────────────────────────────────────────────────

def dock(provider_name, *, probe=False, refresh=False, loader=None,
         offers=None, hermes_home=None):
    """`memrack dock <provider>` — the offer/dock/probe dispatcher.

    probe=True: run probe() and write the DRAFT card (the designed
    `--probe` behaviour). refresh=True: drift-recheck against the card's
    evidence (version change -> card revision note + refreshed values).
    WITHOUT --probe: offer only — NO card is written (design: no
    AUTO-dock; best_for/limits get reviewed by the human between DRAFT
    and final card). Provider not installed: refused, fail-closed,
    Gap-Note. Provider IS active already: refused (not a candidate).

    ``offers``/``loader`` are the test-double seams (see catalog_offers/
    probe); by default the installed set comes from the real discovery.
    """
    offers_list = catalog_offers(offers, hermes_home=hermes_home) \
        if offers is not None else catalog_offers(hermes_home=hermes_home)
    offer = next((o for o in offers_list if o.get("name") == provider_name), None)
    if offer is None:
        return {
            "provider": provider_name, "refused": True,
            "gap": "provider %r is not an installed, INACTIVE catalog memory "
                   "provider (fail-closed — nothing invented; uninstalled "
                   "catalog names do not dock)" % provider_name,
            "hint": "candidates: %s" % (", ".join(
                sorted(o["name"] for o in offers_list)) or "(none)"),
        }
    if offer.get("active"):
        return {
            "provider": provider_name, "refused": True,
            "gap": "provider %r IS the active provider — not a dock candidate"
                   % provider_name,
        }
    if refresh:
        return drift_recheck(provider_name, loader=loader,
                             hermes_home=hermes_home)
    if not probe:
        return {
            "provider": provider_name,
            "status": "offered",
            "offer": {key: offer.get(key)
                      for key in ("name", "source", "version", "dir")},
            "note": "offered only — nothing docked (no AUTO-dock: the "
                    "user/agent decides). Rerun with --probe to probe in "
                    "isolation and write the draft card.",
        }
    report = _probe(provider_name, loader=loader, hermes_home=hermes_home)
    if report.get("error") or report.get("gap"):
        reason = report.get("gap") or report.get("error")
        return {"provider": provider_name, "refused": True,
                "error": reason, "gap": reason}
    if not report.get("available", True):
        return {"provider": provider_name, "refused": True,
                "gap": "provider reports itself unavailable (missing "
                       "credentials/config — fail-closed: docking refused, "
                       "never invented)"}
    card_path = _docked_dir(hermes_home) / ("%s.yaml" % provider_name)
    if card_path.exists():
        try:
            existing = _read_card(card_path) or {}
        except Exception as exc:
            return {"provider": provider_name, "refused": True,
                    "gap": "unreadable card on file (%s: %s) — refusing to "
                           "overwrite (fail-closed); dock remove first"
                           % (type(exc).__name__, exc)}
        if not existing.get("draft"):
            return {"provider": provider_name, "refused": True,
                    "gap": "a REVIEWED card is on file — a probe draft would "
                           "overwrite human card text (fail-closed); run "
                           "--refresh for the drift-recheck instead"}
    written = write_draft_card(provider_name, report, hermes_home=hermes_home)
    return {
        "provider": provider_name, "status": "draft-docked",
        "card_file": written["file"], "shim": written["shim"],
        "classification": report.get("classification"),
        "mirror_tools": report.get("mirror_tools"),
        "evidence": report.get("evidence"),
        "note": "draft card written — best_for/limits wait for the human "
                "review; presence semantics: the dock activates next session",
    }


# ── card management (list / show / remove) ──────────────────────────────────

def dock_list(offers=None, hermes_home=None):
    """`memrack dock list` — offers + cards overview: the installed, inactive
    candidates that are NOT docked yet, plus the cards already present in
    backends.d (draft or reviewed; presence semantics identical to every
    docked backend). ``offers`` is the test-double seam (see catalog_offers)."""
    offered = list(offers) if offers is not None else catalog_offers(hermes_home=hermes_home)
    dock = _docked_dir(hermes_home)
    cards, card_names = [], set()
    if dock.is_dir():
        for path in sorted(dock.glob("*.yaml")):
            row = {"file": path.name, "provider": None, "card": None,
                   "draft": None, "error": None}
            try:
                man = _read_card(path) or {}
            except Exception as exc:
                row["error"] = "unreadable card: %s: %s" % (type(exc).__name__, exc)
                cards.append(row)
                continue
            if not isinstance(man, dict):
                row["error"] = "card carries no mapping"
                cards.append(row)
                continue
            name = str(man.get("name") or "")
            if name:
                card_names.add(name)
                row["provider"] = name
            row["card"] = name
            row["draft"] = bool(man.get("draft"))
            row["module"] = man.get("module") or ""
            row["search"] = list(man.get("search") or [])
            row["mirror_decision"] = man.get("mirror_decision") or ""
            row["mirror_tools"] = dict(man.get("mirror_tools") or {})
            row["evidence"] = dict(man.get("evidence") or {})
            cards.append(row)
    undocked = [o for o in offered if o.get("name") not in card_names]
    out = {"offers": undocked, "cards": cards}
    if offers is None and not offered:
        out["note"] = ("provider discovery unavailable here"
                       "(plugins.memory not importable)" if _plugins_memory() is None
                       else "no installed inactive catalog memory providers")
    return out


def dock_show(provider_name, *, hermes_home=None):
    """`memrack dock show <provider>` — one card's full view INCLUDING the
    mirrored tools' EFFECTIVE names. Design law (Namensgesetz): effective
    names are always visible in the memrack_status card — the status tool
    serves exactly this data."""
    dock = _docked_dir(hermes_home)
    path = dock / ("%s.yaml" % provider_name)
    if not path.exists():
        return {"provider": provider_name, "error": "no card on file",
                "hint": "`memrack dock list` shows what IS docked"}
    try:
        man = _read_card(path) or {}
    except Exception as exc:
        return {"provider": provider_name,
                "error": "unreadable card: %s: %s" % (type(exc).__name__, exc)}
    if not isinstance(man, dict):
        return {"provider": provider_name, "error": "card carries no mapping"}
    out = dict(man)
    out["provider"] = man.get("name") or provider_name
    out["file"] = path.name
    out["draft"] = bool(man.get("draft"))
    out["mirror_tools"] = dict(man.get("mirror_tools") or {})
    out["evidence"] = dict(man.get("evidence") or {})
    return out


def dock_remove(provider_name, *, hermes_home=None):
    """`memrack dock remove <provider>` — leave the rack: the card file is
    removed (presence semantics: rm manifest = registered-removed); the
    parked `disabled-<provider>.yaml` variant leaves too. Idempotent: an
    absent card is an honest report, not an error. (Parking a card instead
    of removing = the established `disabled-` prefix rename convention, a
    file operation the doc covers — no separate machine state.)"""
    dock = _docked_dir(hermes_home)
    removed = False
    for name in (provider_name, "disabled-%s" % provider_name):
        path = dock / ("%s.yaml" % name)
        if path.exists():
            try:
                path.unlink()
                removed = True
            except OSError as exc:
                return {"provider": provider_name, "removed": removed,
                        "error": "card %r not removable: %s" % (path.name, exc)}
    out = {"provider": provider_name, "removed": removed}
    if not removed:
        out["note"] = "no card on file (nothing to remove — idempotent)"
    else:
        out["note"] = ("card removed — presence semantics: the backend "
                       "unregisters; active sessions keep the snapshot")
    return out


# ── drift recheck: the evidence ages, the probe refreshes ───────────────────

def drift_recheck(provider_name, *, loader=None, hermes_home=None):
    """Version drift: compare the INSTALLED provider version against the
    card's probe evidence.

    Version change -> re-probe + card revision note (revised_at + from-
    version -> to-version) + refreshed evidence; same version -> honest
    no-op report (no churn). A version change is exactly when the probe
    evidence and the derived card data may have gone stale. The fail-closed
    discipline: a FAILED re-probe leaves the stale card AS-IS (the last
    proven evidence stays on file) and reports the refusal — the card is
    never silently rewritten. ``loader`` is the test-double seam: the
    doubled provider carries its version where the real path reads the
    provider manifest version.
    """
    card_path = _docked_dir(hermes_home) / ("%s.yaml" % provider_name)
    try:
        card = _read_card(card_path)
    except Exception as exc:
        return {"provider": provider_name, "drifted": False,
                "error": "unreadable card: %s: %s" % (type(exc).__name__, exc)}
    if not card:
        return {"provider": provider_name, "drifted": False,
                "error": "no card on file (not docked)",
                "note": "`memrack dock <provider> --probe` first"}
    old_version = str((card.get("evidence") or {}).get("provider_version") or "")
    if loader is None:
        loader = _real_loader(provider_name)
    try:
        provider = loader()
    except Exception as exc:
        return {"provider": provider_name, "drifted": False,
                "error": "drift check failed: provider not resolvable in "
                         "isolation (fail-closed): %s: %s" % (type(exc).__name__, exc)}
    if provider is None:
        return {"provider": provider_name, "drifted": False,
                "error": "drift check failed: provider not installed/loadable "
                         "(fail-closed; the card keeps its last proven evidence)"}
    installed = _provider_version(provider_name, provider)
    available = _available_of(provider)
    if not available:
        return {"provider": provider_name, "drifted": False,
                "error": "provider reports itself unavailable (fail-closed; "
                         "no card revision without a proven provider)"}
    if installed == old_version:
        return {"provider": provider_name, "drifted": False,
                "version": installed,
                "note": "same version — the probe evidence stays (no churn)"}
    report = probe(provider_name, loader=loader, hermes_home=hermes_home)
    if report.get("error") or report.get("gap"):
        return {"provider": provider_name, "drifted": True,
                "from_version": old_version, "to_version": installed,
                "error": report.get("error") or report.get("gap"),
                "note": "re-probe refused (fail-closed): the card keeps its "
                        "last proven evidence; fix/remove the dock"}
    # apply the FRESH derivation, record the revision hop; card claims the
    # machine does not re-derive (human-authored modes/bridge text) SURVIVE —
    # a refresh never silently un-authors the card's retrieval claims
    fresh_modes = list(report.get("derived_search_modes") or [])
    if fresh_modes:
        card["search"] = fresh_modes
    fresh_mapping = {entry["tool"]: entry["effective"]
                     for entry in (report.get("mirror_tools") or [])}
    if fresh_mapping:
        card["mirror_tools"] = fresh_mapping
        card["mirror_decision"] = "mirror"
    else:
        card.pop("mirror_tools", None)
        card.pop("mirror_decision", None)
    card["evidence"] = dict(report.get("evidence") or {})
    revision = card.get("revisions") if isinstance(card.get("revisions"), list) else []
    import yaml   # lazy: pyyaml at the point of use (the registry convention)
    revisions = list(revision)
    revisions.append({"from_version": old_version, "to_version": installed,
                      "revised_at": _utcnow_iso()})
    card["revisions"] = revisions
    _atomic_write(card_path, yaml.dump(card, default_flow_style=False,
                                       allow_unicode=True, sort_keys=False))
    return {"provider": provider_name, "drifted": True,
            "from_version": old_version, "to_version": installed,
            "revised": True,
            "note": "card re-derived from the fresh probe; human best_for/"
                    "limits text untouched"}
